const fs = require('node:fs');
const { chromium } = require('C:/Users/massa/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const baseUrl = process.argv[2] || 'http://localhost:8087';
(async () => {
  const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] }).catch(() => chromium.launch({ channel: 'msedge', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] }));
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce', serviceWorkers: 'block' });
  const errors = [], missing = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  page.on('response', response => { if (response.status() >= 400) missing.push({ status: response.status(), url: response.url() }); });
  const check = (name, result) => { if (!result) throw new Error(name); checks.push(name); process.stdout.write(name + '\n'); };
  const ready = async id => { await page.locator('#' + id + '[data-state="ready"]').waitFor({ timeout: 45000 }); };
  const selectSlot = async slot => page.locator('#gunsmith-slot-' + slot).click();
  const equip = async (slot, id) => { await selectSlot(slot); await page.locator('#gunsmith-equip-' + slot + '-' + id).click(); await ready('loadout-weapon-model'); };
  const inspect = async (slot, id, filename) => {
    await selectSlot(slot);
    await page.locator('#gunsmith-inspect-' + slot + '-' + id).click();
    await ready('gunsmith-part-model');
    check('3D Inspector: ' + slot + '/' + id, await page.locator('#gunsmith-part-model-viewport canvas').count() === 1);
    if (filename) await page.locator('#gunsmith-inspector').screenshot({ path: '.codex/' + filename, animations: 'disabled' });
  };
  await page.goto(baseUrl, { waitUntil: 'domcontentloaded', timeout: 180000 });
  await page.locator('#gunsmith-panel').waitFor({ timeout: 180000 });
  await page.locator('#loadout-lab').scrollIntoViewIfNeeded();
  await ready('loadout-weapon-model');
  check('Six Independent Rifle Slots', await page.locator('.gunsmith-slot').count() === 6);
  await page.locator('#gunsmith-reset').click();
  await ready('loadout-weapon-model');
  await page.locator('#loadout-preview').screenshot({ path: '.codex/gunsmith-factory.png', animations: 'disabled' });
  await equip('optic', 'reflex');
  await inspect('optic', 'reflex', 'gunsmith-reflex-inspector.png');
  await page.locator('#gunsmith-inspector-close').click();
  const opticBefore = await page.locator('#gunsmith-slot-value-optic').innerText();
  await inspect('optic', 'precision', 'gunsmith-scope-inspector.png');
  check('Inspection Does Not Equip', (await page.locator('#gunsmith-slot-value-optic').innerText()) === opticBefore);
  await page.locator('#gunsmith-part-model-zoom-in').click();
  check('Inspector Zoom', Number(await page.locator('#gunsmith-part-model-viewport').getAttribute('data-zoom')) > 1);
  await page.locator('#gunsmith-inspector-equip').click();
  await page.locator('#gunsmith-inspector').waitFor({ state: 'detached' });
  await equip('muzzle', 'suppressor');
  await equip('underbarrel', 'grip');
  await equip('rail', 'light');
  await equip('stock', 'cheek-rest');
  await equip('magazine', 'extended');
  check('All Six Parts Equipped Together', (await page.locator('#gunsmith-count').innerText()).startsWith('6 / 6'));
  const fullEquipment = await page.locator('#loadout-weapon-model').getAttribute('data-equipment');
  await page.locator('#loadout-lab').scrollIntoViewIfNeeded();
  await page.locator('#loadout-builder').screenshot({ path: '.codex/gunsmith-desktop.png', animations: 'disabled' });
  await page.locator('#loadout-preview').screenshot({ path: '.codex/gunsmith-mounted.png', animations: 'disabled' });
  await page.locator('#loadout-weapon-model-zoom-in').click();
  check('Mounted Build Zoom', Number(await page.locator('#loadout-weapon-model-viewport').getAttribute('data-zoom')) > 1);
  await page.locator('#loadout-weapon-model-reset').click();
  for (const [slot, id] of [['muzzle','suppressor'],['muzzle','brake'],['underbarrel','grip'],['underbarrel','bipod'],['rail','light'],['stock','cheek-rest'],['magazine','extended']]) {
    await inspect(slot, id, slot === 'rail' ? 'gunsmith-light-inspector.png' : undefined);
    await page.locator('#gunsmith-inspector-close').click();
  }
  await selectSlot('rail');
  await page.locator('#gunsmith-equip-rail-light').click();
  const afterRemove = await page.locator('#loadout-weapon-model').getAttribute('data-equipment');
  check('Remove One Slot Preserves Other Parts', afterRemove === fullEquipment.replace('/light/', '/none/'));
  await equip('rail','light');
  await page.locator('#loadout-name-input').fill('Gunsmith Six Slot Check');
  await page.locator('#loadout-save').click();
  await page.locator('.saved-loadout').waitFor();
  const key = 'weapon-database:v1:armory';
  const stored = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
  const record = stored.loadouts[0];
  check('Saved Record Includes All Slots', record.optic === 'precision' && record.muzzle === 'suppressor' && record.underbarrel === 'grip' && record.rail === 'light' && record.stock === 'cheek-rest' && record.magazine === 'extended');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.saved-loadout-action').first().click();
  await ready('loadout-weapon-model');
  check('Reload And Edit Restore All Parts', await page.locator('#loadout-weapon-model').getAttribute('data-equipment') === fullEquipment);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#loadout-lab').scrollIntoViewIfNeeded();
  await page.locator('#loadout-preview').screenshot({ path: '.codex/gunsmith-mobile-preview.png', animations: 'disabled' });
  await selectSlot('optic');
  await page.locator('#gunsmith-panel').screenshot({ path: '.codex/gunsmith-mobile-panel.png', animations: 'disabled' });
  check('Mobile Page Fits Viewport', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  await inspect('optic','reflex','gunsmith-mobile-inspector.png');
  check('Mobile Inspector Fits Viewport', await page.locator('#gunsmith-inspector').evaluate(el => el.getBoundingClientRect().width <= innerWidth));
  await page.locator('#gunsmith-inspector-close').click();
  await page.evaluate(({key, record}) => {
    const legacy = { ...record, attachment: 'suppressor' };
    for (const slot of ['muzzle','underbarrel','rail','stock','magazine','customization']) delete legacy[slot];
    localStorage.setItem(key, JSON.stringify({ counter: legacy.number, schemaVersion: 1, loadouts: [legacy], savedWeapons: [] }));
  }, {key, record});
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.saved-loadout-action').first().click();
  await ready('loadout-weapon-model');
  check('Legacy Attachment Migrates To Muzzle', (await page.locator('#gunsmith-slot-value-muzzle').innerText()) === 'Suppressor');
  await selectSlot('muzzle');
  await page.locator('#gunsmith-equip-muzzle-suppressor').click();
  await page.locator('#loadout-save').click();
  await page.waitForFunction(key => JSON.parse(localStorage.getItem(key)).loadouts[0].muzzle === 'none', key);
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.saved-loadout-action').first().click();
  await ready('loadout-weapon-model');
  check('Explicit Removal Overrides Legacy Value After Reload', (await page.locator('#gunsmith-slot-value-muzzle').innerText()) === 'Factory Muzzle');
  await page.setViewportSize({ width: 1440, height: 1050 });
  for (const [weaponId, slot, id] of [['aurelius-longsword','customization','scabbard'],['kestrel-quad','customization','camera'],['vanguard-compound','optic','precision']]) {
    await page.locator('#loadout-weapon-input').selectOption(weaponId);
    await ready('loadout-weapon-model');
    await inspect(slot,id, weaponId === 'kestrel-quad' ? 'gunsmith-camera-inspector.png' : undefined);
    await page.locator('#gunsmith-inspector-close').click();
    if ((await page.locator('#gunsmith-slot-value-' + slot).innerText()) !== (slot === 'optic' ? 'Precision Scope' : id === 'camera' ? 'Camera Pod' : 'Scabbard')) await equip(slot,id);
    await ready('loadout-weapon-model');
  }
  process.stdout.write(JSON.stringify({ errors, missing }) + '\n');
  check('No Browser Runtime Errors', errors.length === 0);
  const result = { baseUrl, checks, errors, missing, equipment: fullEquipment };
  fs.writeFileSync('.codex/gunsmith-production-verification.json', JSON.stringify(result, null, 2));
  process.stdout.write(JSON.stringify(result) + '\n');
  await browser.close();
})().catch(error => { process.stderr.write(error.stack + '\n'); process.exit(1); });
